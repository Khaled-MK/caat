   function translateNode(node, targetLanguage) {
      if (node.nodeType === Node.TEXT_NODE) {
         if (node.parentElement?.closest("[data-no-translate]")) return;
         const text = node.nodeValue ?? "";
         const trimmed = text.trim();
         if (!trimmed) return;
         const translated = translateText(trimmed, targetLanguage);
         if (translated !== trimmed) {
            node.nodeValue = text.replace(trimmed, translated);
         }
         return;
      }
      if (node.nodeType !== Node.ELEMENT_NODE) return;

      const element = node;
      if (element.hasAttribute("data-no-translate")) return;
      ["placeholder", "title", "aria-label", "alt"].forEach((attribute) => {
         const value = element.getAttribute(attribute);
         if (value) element.setAttribute(attribute, translateText(value, targetLanguage));
      });
      if (element.tagName === "INPUT" && element.type === "button" && element.value) {
         element.value = translateText(element.value, targetLanguage);
      }
      element.childNodes.forEach((child) => translateNode(child, targetLanguage));
   }

   function applyLanguage(targetLanguage) {
      language = targetLanguage;
      document.documentElement.lang = language;
      document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
      const title = document.querySelector("head title");
      if (title) translateNode(title, language);
      translateNode(document.body, language);

      const languageButton = document.getElementById("language-switch");
      if (languageButton) {
         languageButton.textContent = language === "ar" ? "FR" : "AR";
         languageButton.setAttribute("aria-label", language === "ar" ? "التبديل إلى الفرنسية" : "Passer en arabe");
      }
      localStorage.setItem(languageKey, language);
      document.dispatchEvent(new CustomEvent("app-language-changed", { detail: { language } }));
   }

   const languageButton = document.getElementById("language-switch");
   if (languageButton) {
      languageButton.addEventListener("click", () => applyLanguage(language === "ar" ? "fr" : "ar"));
   }

   const observer = new MutationObserver((records) => {
      records.forEach((record) => {
         if (record.type === "characterData") {
            translateNode(record.target, language);
         } else {
            record.addedNodes.forEach((node) => translateNode(node, language));
         }
      });
   });
   observer.observe(document.body, { childList: true, characterData: true, subtree: true });
   applyLanguage(language);

